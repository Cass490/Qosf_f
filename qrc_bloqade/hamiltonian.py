import numpy as np
import bloqade
from bloqade import rydberg_h

class rydberg:
    def __init__(self, n_sites, omega, V, detuning_values=None):
        self.n_sites = n_sites
        self.omega = omega
        self.V = V #interaction parameters
        if detuning_values is None:
            self.detuning_values = np.zeros(n_sites)
        else:
            if len(detuning_values) != n_sites:
                raise ValueError(f"Length of detuning_values ({len(detuning_values)}) "
                               f"must match n_sites ({n_sites})")
            self.detuning_values = np.array(detuning_values)
        self.positions = [[0, i] for i in range(self.n_sites)]  # Define positions HERE
        self.hamiltonian= self.get_hamiltonian()
    
    def get_hamiltonian(self):
        #    The positions of the atoms/qubits are given here.
        h = bloqade.rydberg.rydberg_h(self.positions)

        # 2. Add the DRIVING FIELD (Rabi term).
        #    - amplitude:  The strength of the driving field (omega / 2).
        #    - phase:      Set to 0 for an X-rotation (Bloqade convention).
        #    - detuning:   Set to 0 for the *global* driving field.
        h = h.driving_field(amplitude=self.omega / 2, phase=0, detuning=0)

        # 3. Add the DETUNING FIELD (site-specific).
        h = h.detuning_field(self.detuning_values / 2)

        return h
            
    def apply_dynamics(self, encoded_states, time=1.0): #simulate system time evolution
                results=[]
                for init_state in encoded_states:
                  result = bloqade.simulate(
                  init_state,
                  hamiltonian=self.hamiltonian,
                  duration=time,
                  steps=100
            )
                  results.append(result)
            
                return results








































































































































































































































































































































































































